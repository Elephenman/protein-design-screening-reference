def expand(short):
    row = dict(DEFAULTS)
    row.update(short)
    full = OrderedDict()
    for k, header in KEYMAP.items():
        full[header] = row.get(k, NA)
    if full["链接(url)"] in ("", NA) and full["DOI(doi)"] != NA:
        full["链接(url)"] = "https://doi.org/" + full["DOI(doi)"]
    if not full["链接(url)"]:
        full["链接(url)"] = NA
    return full


def build():
    rows = OrderedDict()
    order = []
    for c in BAKER_CARDS + ZHOU_CARDS + CAO_CARDS:
        e = expand(c)
        rows[e["编号(id)"]] = e
        order.append(e["编号(id)"])
    for dst_id, src_id in MERGED:
        if src_id not in rows or dst_id not in rows:
            raise SystemExit("合并表引用的卡片缺失: %s / %s" % (src_id, dst_id))
        src, dst = rows[src_id], rows[dst_id]
        dst["编号(id)"] = "%s; %s" % (dst_id, src_id)
        if src["人物组(group)"] not in dst["人物组(group)"]:
            dst["人物组(group)"] += "; " + src["人物组(group)"]
        # 只补空字段；已有原文数字不覆盖，避免改动数字
        for h in HEADERS:
            if h in ("编号(id)", "人物组(group)"):
                continue
            if dst[h] in (NA, "", "未标注") and src[h] not in (NA, "", "未标注"):
                dst[h] = src[h]
        del rows[src_id]
        order.remove(src_id)
    for cid, (note, extra) in PATCHES.items():
        row = rows[cid]
        row["cost"] = note
        if extra and extra not in row["人物组(group)"]:
            row["人物组(group)"] += "; " + extra
    for k in K_ROWS:
        e = expand(k)
        rows[e["编号(id)"]] = e
        order.append(e["编号(id)"])
    return [rows[i] for i in order], list(MERGED)


NA_COL = "未记录"
V_COL = "核验状态(doi_verified)"


def normalize_rows(rows):
    """归一化占位符：『不适用』只允许出现在 核验状态(doi_verified) 列，
    其余列一律写 未记录（任务规范：原文没有的字段留 未记录/UNKNOWN）。"""
    for r in rows:
        for h in HEADERS:
            if h == V_COL:
                continue
            if r[h] == "不适用":
                r[h] = NA_COL
    return rows


def write_csv(rows):
    with open(OUT, "w", newline="", encoding="utf-8-sig") as fh:
        w = csv.DictWriter(fh, fieldnames=HEADERS, quoting=csv.QUOTE_MINIMAL,
                           extrasaction="raise")
        w.writeheader()
        for r in rows:
            w.writerow({h: ("" if r[h] is None else str(r[h])) for h in HEADERS})


def source_ids():
    pats = [("baker.md", BK, r"^### \[(B\d{2})\]"),
            ("zhou.md", ZH, r"^### \[(Z\d{2})\]"),
            ("cao.md", CA, r"^### \[(C\d{2})\]")]
    res = []
    for fn, grp, pat in pats:
        ids = []
        with open(os.path.join(SRC, fn), encoding="utf-8") as fh:
            for ln in fh:
                m = re.match(pat, ln.strip())
                if m:
                    ids.append(m.group(1))
        res.append((fn, grp, ids))
    return res


def gate_check(rows, merged):
    print("=== 门禁自检 ===")
    print("总行数: %d" % len(rows))
    cnt = Counter(r["人物组(group)"] for r in rows)
    print("--- 各 group 行数(group 列原值) ---")
    for g, n in sorted(cnt.items(), key=lambda x: (-x[1], x[0])):
        print("  %-30s %d" % (g, n))
    prim = Counter(r["人物组(group)"].split(";")[0].strip() for r in rows)
    print("--- 按主组归并 ---")
    for g, n in sorted(prim.items(), key=lambda x: (-x[1], x[0])):
        print("  %-12s %d" % (g, n))
    print("--- 完整性核对: 源文件卡片标题数 vs CSV 覆盖 ---")
    covered = set()
    for r in rows:
        for p in r["编号(id)"].split(";"):
            covered.add(p.strip())
    tot = 0
    for fn, grp, ids in source_ids():
        miss = [i for i in ids if i not in covered]
        tot += len(ids)
        print("  %-10s (%s) 源卡片 %2d 张 / CSV 覆盖 %2d 张 / 缺失 %s"
              % (fn, grp, len(ids), len(ids) - len(miss), miss or "无"))
    print("  源卡片合计 %d 张; 跨组同 DOI 合并 %d 组(%s) -> 卡片行 %d 行"
          % (tot, len(merged), ", ".join("%s→%s" % m for m in merged), tot - len(merged)))
    krows = [r for r in rows if r["编号(id)"].split(";")[0].startswith("K")]
    print("  cost-benchmarks.md 无 ### [Xnn] 卡片，按证据条目抽 %d 行(K01…)" % len(krows))
    ok = set(r["编号(id)"] for r in rows
             if re.match(r"^10\.\d{4,}/", r["DOI(doi)"]) or r["DOI(doi)"].startswith("arXiv:"))
    print("--- DOI 非空且格式合法(^10\\.\\d{4,}/ 或 arXiv:): %d / %d 行 ---" % (len(ok), len(rows)))
    bad = [(r["编号(id)"], r["DOI(doi)"]) for r in rows
           if r["DOI(doi)"] != NA and r["编号(id)"] not in ok]
